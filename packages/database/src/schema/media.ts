/**
 * Media (§9, §10, §11, §30).
 *
 * Three tables, each answering one question:
 *
 *   media_assets      — what is this file, where are its bytes, and where did
 *                       it come from? (§10 provenance lives here, on the row.)
 *   media_derivatives — the thumbnails and previews generated from it.
 *   media_usages      — which content records use it, and in what role? A
 *                       many-to-many join, because the same screenshot is
 *                       legitimately the primary image of a page *and* the
 *                       before-state of an interaction.
 *
 * No binary column appears anywhere here. Bytes live in object storage and the
 * row holds `storage_key` (§9). What the relational database stores is the
 * *identity, provenance and relationships* of a file — which is exactly the
 * part that has to be queryable, and exactly the part object storage cannot do.
 */
import { relations, sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  index,
  integer,
  jsonb,
  pgTable,
  primaryKey,
  text,
  uniqueIndex,
} from "drizzle-orm/pg-core";
import {
  actorId,
  createdAt,
  deletedAt,
  fk,
  perceptualHash,
  primaryId,
  searchVectorSql,
  timestamptz,
  tsvector,
  updatedAt,
} from "./columns.js";
import {
  captureMethodEnum,
  deviceClassEnum,
  mediaDerivativeKindEnum,
  mediaKindEnum,
  mediaScanStatusEnum,
  mediaStatusEnum,
  mediaUploadSourceEnum,
  mediaUsageRoleEnum,
  screenshotScopeEnum,
} from "./enums.js";
import { users } from "./identity.js";
import { sources } from "./sources.js";

export const mediaAssets = pgTable(
  "media_assets",
  {
    id: primaryId(),
    kind: mediaKindEnum("kind").notNull(),
    status: mediaStatusEnum("status").notNull().default("pending"),

    // --- Storage location -------------------------------------------------
    /** Which driver holds the bytes: `local` in development, `s3` in production. */
    storageDriver: text("storage_driver").notNull(),
    storageBucket: text("storage_bucket"),
    /** Key within the bucket. Generated by us and never derived from an
     * uploaded filename, so a crafted filename cannot escape its prefix. */
    storageKey: text("storage_key").notNull(),

    // --- File identity ----------------------------------------------------
    /** Sniffed from magic bytes, never taken from the client's claim. */
    mimeType: text("mime_type").notNull(),
    /** Preserved for display only. Never used to build a path or a type. */
    originalFilename: text("original_filename"),
    byteSize: bigint("byte_size", { mode: "number" }).notNull(),
    width: integer("width"),
    height: integer("height"),
    durationMs: integer("duration_ms"),
    hasAlpha: boolean("has_alpha"),
    isAnimated: boolean("is_animated"),
    colorProfile: text("color_profile"),
    dominantColorHex: text("dominant_color_hex"),

    // --- Deduplication (§11) ---------------------------------------------
    /**
     * sha256 of the file bytes. The exact-duplicate key: a re-crawl that
     * produces a byte-identical screenshot reuses this row rather than storing
     * the file again, and records a new capture pointing at it.
     */
    sha256: text("sha256").notNull(),
    /**
     * 64-bit difference hash. Screenshots of the same page taken minutes apart
     * differ in a few bytes (a timestamp, an ad, an animation frame) so sha256
     * misses them; a perceptual hash catches near-duplicates by Hamming
     * distance. Advisory only — it flags a suspected duplicate for review
     * rather than discarding anything (§11 pairs dedupe with versioning, not
     * deletion).
     */
    perceptualHash: perceptualHash("perceptual_hash"),

    // --- Provenance (§10) — the whole point of this block -----------------
    /** Where the depicted thing lives. Null for a manual upload. */
    sourceUrl: text("source_url"),
    originDomain: text("origin_domain"),
    sourceId: fk("source_id").references(() => sources.id, { onDelete: "set null" }),
    /** The content record this was captured *for*. FK added in migration 0001
     * to break the media <-> content circular reference. */
    parentContentId: fk("parent_content_id"),
    /** The crawl job and capture that produced it. FKs added in migration 0001. */
    crawlJobId: fk("crawl_job_id"),
    captureId: fk("capture_id"),
    captureMethod: captureMethodEnum("capture_method").notNull().default("manual_upload"),
    uploadSource: mediaUploadSourceEnum("upload_source").notNull().default("manual_upload"),
    /** Exact conditions of capture, so a recapture is comparable (§12). */
    capturedAt: timestamptz("captured_at"),
    viewportWidth: integer("viewport_width"),
    viewportHeight: integer("viewport_height"),
    deviceScaleFactor: integer("device_scale_factor"),
    deviceProfile: text("device_profile"),
    deviceClass: deviceClassEnum("device_class"),
    browserName: text("browser_name"),
    browserVersion: text("browser_version"),
    screenshotScope: screenshotScopeEnum("screenshot_scope"),

    // --- Editorial metadata (§9) -----------------------------------------
    title: text("title"),
    altText: text("alt_text"),
    caption: text("caption"),
    internalNotes: text("internal_notes"),

    // --- Upload validation ------------------------------------------------
    scanStatus: mediaScanStatusEnum("scan_status").notNull().default("pending"),
    /** Why an upload was rejected. Set with status = 'quarantined'. */
    scanNotes: text("scan_notes"),
    /** Extra format-specific facts from the decoder. */
    metadata: jsonb("metadata").$type<Record<string, unknown>>().notNull().default({}),

    /** Maintained on write from media_usages, so the library can show
     * "unused" without a correlated subquery per row. */
    usageCount: integer("usage_count").notNull().default(0),

    uploadedBy: actorId("uploaded_by").references(() => users.id, { onDelete: "set null" }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    archivedAt: timestamptz("archived_at"),
    /** Set when the bytes are removed from storage. The row itself stays, so
     * "where did this screenshot come from?" is still answerable afterwards. */
    bytesDeletedAt: timestamptz("bytes_deleted_at"),
    deletedAt: deletedAt(),

    searchVector: tsvector("search_vector").generatedAlwaysAs(
      searchVectorSql({
        A: ["title", "original_filename"],
        B: ["alt_text", "origin_domain"],
        C: ["caption", "source_url"],
        D: ["internal_notes"],
      }),
    ),
  },
  (t) => [
    // The exact-dedupe index. Partial on live rows so a deleted file's hash
    // does not block re-uploading the same image later.
    uniqueIndex("media_sha256_key")
      .on(t.sha256)
      .where(sql`${t.deletedAt} is null`),
    index("media_phash_idx")
      .on(t.perceptualHash)
      .where(sql`${t.perceptualHash} is not null and ${t.deletedAt} is null`),
    index("media_kind_idx").on(t.kind),
    index("media_status_idx").on(t.status),
    index("media_created_idx").on(t.createdAt.desc()),
    index("media_captured_idx").on(t.capturedAt.desc().nullsLast()),
    index("media_source_idx").on(t.sourceId),
    index("media_parent_content_idx").on(t.parentContentId),
    index("media_crawl_job_idx").on(t.crawlJobId),
    index("media_capture_idx").on(t.captureId),
    index("media_mime_idx").on(t.mimeType),
    index("media_origin_domain_idx").on(t.originDomain),
    index("media_byte_size_idx").on(t.byteSize.desc()),
    // "Unused media" — a real housekeeping view in a library this size.
    index("media_unused_idx")
      .on(t.createdAt.desc())
      .where(sql`${t.usageCount} = 0 and ${t.deletedAt} is null`),
    index("media_search_idx").using("gin", t.searchVector),
    uniqueIndex("media_storage_key_key").on(t.storageDriver, t.storageKey),
  ],
);

/**
 * Generated renditions.
 *
 * Separate rows rather than columns on `media_assets` because the set of sizes
 * is expected to change: adding an AVIF rendition or a new breakpoint should be
 * a backfill job, not a migration plus a column per format per size.
 */
export const mediaDerivatives = pgTable(
  "media_derivatives",
  {
    id: primaryId(),
    mediaId: fk("media_id")
      .notNull()
      .references(() => mediaAssets.id, { onDelete: "cascade" }),
    kind: mediaDerivativeKindEnum("kind").notNull(),
    storageKey: text("storage_key").notNull(),
    mimeType: text("mime_type").notNull(),
    width: integer("width").notNull(),
    height: integer("height").notNull(),
    byteSize: bigint("byte_size", { mode: "number" }).notNull(),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex("media_derivative_key").on(t.mediaId, t.kind),
    index("media_derivative_media_idx").on(t.mediaId),
  ],
);

/**
 * Which records use which media, and in what role (§9 "usage", §30 "content
 * usage").
 *
 * This is what makes the media detail page able to answer "where is this
 * used?", and what makes deleting a file safe to reason about: a file with
 * usages is one an operator is warned about before removing.
 */
export const mediaUsages = pgTable(
  "media_usages",
  {
    mediaId: fk("media_id")
      .notNull()
      .references(() => mediaAssets.id, { onDelete: "cascade" }),
    /** FK added in migration 0001 (circular with media_assets). */
    contentItemId: fk("content_item_id").notNull(),
    role: mediaUsageRoleEnum("role").notNull().default("attachment"),
    position: integer("position").notNull().default(0),
    createdBy: actorId("created_by").references(() => users.id, { onDelete: "set null" }),
    createdAt: createdAt(),
  },
  (t) => [
    primaryKey({ columns: [t.mediaId, t.contentItemId, t.role] }),
    index("media_usage_content_idx").on(t.contentItemId),
    index("media_usage_media_idx").on(t.mediaId),
  ],
);

export const mediaAssetsRelations = relations(mediaAssets, ({ one, many }) => ({
  source: one(sources, { fields: [mediaAssets.sourceId], references: [sources.id] }),
  uploader: one(users, { fields: [mediaAssets.uploadedBy], references: [users.id] }),
  derivatives: many(mediaDerivatives),
  usages: many(mediaUsages),
}));

export const mediaDerivativesRelations = relations(mediaDerivatives, ({ one }) => ({
  media: one(mediaAssets, { fields: [mediaDerivatives.mediaId], references: [mediaAssets.id] }),
}));

export const mediaUsagesRelations = relations(mediaUsages, ({ one }) => ({
  media: one(mediaAssets, { fields: [mediaUsages.mediaId], references: [mediaAssets.id] }),
}));

export type MediaAssetRow = typeof mediaAssets.$inferSelect;
export type MediaAssetInsert = typeof mediaAssets.$inferInsert;
export type MediaDerivativeRow = typeof mediaDerivatives.$inferSelect;
