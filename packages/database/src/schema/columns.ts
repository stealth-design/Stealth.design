/**
 * Shared column builders and custom types.
 *
 * Defining these once means every table spells "created_at" the same way, and
 * that the full-text search column is constructed identically everywhere it
 * appears — which matters, because a `tsvector` generated column has to be
 * byte-identical between the schema and the migration to avoid a spurious diff.
 */
import { sql } from "drizzle-orm";
import { customType, timestamp, uuid } from "drizzle-orm/pg-core";

/**
 * Postgres `tsvector`.
 *
 * Drizzle has no native tsvector, so this is a thin custom type. The value is
 * never read or written by application code — the column is
 * GENERATED ALWAYS, maintained by Postgres — but declaring it lets Drizzle
 * create the column and lets queries reference it for `@@` matching.
 */
export const tsvector = customType<{ data: string; driverData: string; notNull: false }>({
  dataType() {
    return "tsvector";
  },
});

/**
 * A 64-bit perceptual hash, stored as 16 lowercase hex characters.
 *
 * `char(16)` rather than `bytea` so that near-duplicate lookups can use a
 * plain equality index for exact matches, and so the value is legible in the
 * CMS when an operator is investigating why two captures were deduplicated.
 * Hamming-distance search is done in application code over a candidate set.
 */
export const perceptualHash = customType<{ data: string; driverData: string }>({
  dataType() {
    return "char(16)";
  },
});

/** `timestamptz`, JS `Date` in and out. Always store UTC; render in local time. */
export const timestamptz = (name: string) => timestamp(name, { withTimezone: true, mode: "date" });

/** Row creation time, set by the database so it cannot be back-dated by a caller. */
export const createdAt = () => timestamptz("created_at").notNull().defaultNow();

/**
 * Last-modified time.
 *
 * Set by the application on every update. There is deliberately no trigger:
 * bulk operations sometimes need to touch thousands of rows without moving
 * `updated_at` (a re-index, a backfill), and a trigger would make that
 * impossible while also making "who changed this and when" less predictable
 * than the audit log.
 */
export const updatedAt = () => timestamptz("updated_at").notNull().defaultNow();

/**
 * Soft delete marker.
 *
 * Content, media and sources are never hard-deleted from the CMS. Provenance
 * (§10, §22) requires that we can always answer "where did this come from and
 * what happened to it", including for things we removed. Media *bytes* are
 * deletable — that is `media_assets.status = 'deleted'` — but the row that
 * records the file's origin stays.
 */
export const deletedAt = () => timestamptz("deleted_at");

/** Primary key: time-ordered UUIDv7 generated by the application (see `uuidv7`). */
export const primaryId = () => uuid("id").primaryKey();

/**
 * A foreign-key column. Nullability and the `references()` clause are the
 * caller's decision, since they vary per relationship.
 */
export const fk = (name: string) => uuid(name);

/**
 * An actor reference. Always nullable: worker and system actions have no user
 * behind them, and a user who is later deleted must not take their audit trail
 * with them (these are `on delete set null`, never cascade).
 */
export const actorId = (name: string) => uuid(name);

/**
 * Build the SQL for an English full-text search vector over weighted fields.
 *
 * Weights follow Postgres convention: A is the most significant. Titles and
 * names get A, structured identifiers (slug, domain, company) get B, longer
 * prose gets C, and incidental text gets D. This ordering is what makes a
 * search for "stripe" rank the Stripe source above a page that merely mentions
 * Stripe in its description.
 *
 * Every argument is passed through `coalesce(..., '')` because `to_tsvector`
 * of NULL is NULL, which would blank the whole vector for one missing field.
 */
export function searchVectorSql(weighted: { A?: string[]; B?: string[]; C?: string[]; D?: string[] }) {
  const parts: string[] = [];
  for (const weight of ["A", "B", "C", "D"] as const) {
    const columns = weighted[weight];
    if (!columns || columns.length === 0) continue;
    const joined = columns.map((c) => `coalesce(${c}, '')`).join(" || ' ' || ");
    parts.push(`setweight(to_tsvector('english', ${joined}), '${weight}')`);
  }
  return sql.raw(parts.join(" || "));
}
